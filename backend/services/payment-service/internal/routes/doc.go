//
// 只有一条路由，但它与这个仓库里其余的 routes 包有一条**相反**的约定：这里的入口是
// **故意不挂认证**的。
//
// 渠道回调没有我们的令牌，它带的是自己的签名——所以「认证」在这条路上的等价物是验签，
// 而验签发生在 service 里、发生在碰报文任何一个字段之前。挂 auth.Middleware 只会让每一次
// 回调都 401，而且是**安静地**失败：渠道那边看到的是「对面没收下」，我们这边看到的是一张
// 永远停在 pending 的支付单。
//
// 其余约定与别的服务一致：路径注册顺序从长到短（底层是 gorilla/mux，按注册顺序取第一个
// 匹配），装配处注入依赖，本包不自己 new 任何东西。
