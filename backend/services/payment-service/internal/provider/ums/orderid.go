package ums

import "strings"

// 这一族渠道对**商户订单号**有一条账户级的格式要求：它必须以渠道那边登记的 sourceCode 开头。
//
// 这条要求是硬的，而且是账户自己的规则、不是文档里的建议：2026-09-21 拿真实账户打过一次 H5，
// 我们发出去的是裸支付单号，银联商务的收银台直接把人挡在门外——
//
//	处理失败: 无效订单号，订单号必须以3CYM开头
//
// 所以本适配器**出去与回来的每一个商户账单号都要过这一对函数**——支付单号与退款单号都算：
//
//	出去   p.channelOrderID(paymentNo)    发起（小程序 / H5）、查单、退款、退款查询、关单
//	回来   p.paymentNoOf(merOrderId)      支付结果通知、结果页回跳、查单与退款查询的回显比对
//
// **退款单号（refundOrderId）走的是同一条规则**，见文件末尾那一节。
//
// 漏掉出口，那次调用会被渠道拒（症状是用户看到「无效订单号」）；漏掉入口，回调会认不出是
// 哪一单（症状是钱收了、单子永远停在待支付）；漏掉**退款**那条出口更隐蔽——退款的 merOrderId
// 指的是要退的那一笔支付，编码方式与发起时不一致时，渠道会认为我们在退一张不存在的单。
// 这就是为什么它是「每一处」而不只是下单那两处。
//
// # 为什么不在支付单号本身上加前缀
//
// 那样能省掉一整层转换，代价是把渠道的账户标识写进**所有**支付单的主键——包括根本不经过渠道的
// 咖啡豆支付——而且以后换一个 sourceCode，历史单号与新单号会分成两种形状。前缀是「这一族渠道
// 怎么称呼我们」这件事，属于适配器，不属于支付单。
//
// # 为什么 merOrderId 不直接用订单号
//
// 老系统正是那么干的（`umspay_service.go:103` 那一行 `"msgId": req.OrderNo, "merOrderId": req.OrderNo`），
// 一笔订单只有一个渠道单号。V2 允许同一笔订单重试支付（见 service.retireAbandonedPayment），
// 每一次尝试有自己的 payment_no——拿它当 merOrderId，渠道侧的两笔尝试才是两笔而不是互相覆盖。
// 所以这里转的是 payment_no，不是 order_no。

// channelOrderID 把内部单号编成渠道侧的商户账单号。
//
// 参数是**支付单号或退款单号**——规范对两者是同一条规则（见文件末尾那一节），所以这里一个
// 函数管两个，而不是写两份迟早会漂开的复制品。
//
// 不 TrimSpace、也不判空：这两个单号都是本服务自己生成的（见 service.Options 的
// NewPaymentNo / NewRefundNo），而 sourceCode 在 Parse 那一步就是必填的（见 config.go 里
// `RequireString("sourceCode")`）。这两个前提都成立时这个函数没有失败的方式；不成立时该修的
// 是那两个前提，不是在这里糊一个兜底。
func (p *Protocol) channelOrderID(internalNo string) string {
	return p.sourceCode + internalNo
}

// paymentNoOf 把渠道侧的商户账单号解回内部单号（支付单号或退款单号）。
//
// # 前缀不是我们的时，原样返回
//
// 比如别家商户的单被打到我们这个账户上。那个值当然不是我们的支付单号，但把它交下去，服务层
// 会走到「查不到这一单」那条既有分支上：记一行 ignored、回一条成功应答、支付状态一个字段都
// 不动——那正是这种情况该有的处置。在这里报错只会把它变成一条渠道会**永远重投**的拒收
// （normalizeCallback 里对同一种权衡有一段更长的注释）。
//
// # 顺带买到的向后兼容
//
// 这条改动之前发出去、且渠道还没结清的旧单，它们的 merOrderId 是不带前缀的裸支付单号。
// TrimPrefix 在前缀不匹配时原样返回，于是那些单的回调仍然认得出来——收口这一次不会把
// 手上还没结的单证丢在半路上。
func (p *Protocol) paymentNoOf(merOrderID string) string {
	return strings.TrimPrefix(merOrderID, p.sourceCode)
}

// # refundOrderId 用同一对函数（2026-09-21 定稿）
//
// 退款单号也要带前缀，**这条有规范原文**：《全民付移动支付 H5支付》v20221020 附带的官方样例
// `H5Pay/Refund.java` 头注释写着——
//
//	退款订单号refundOrderId也需遵循商户订单号生成规范，即以银商分配的4位来源编号作为账单号
//	的前4位，且在商户系统中此账单号保证唯一。总长度需大于6位，小于28位。
//
// 老系统那条同款检查（`admin/services/refund_service.go:667` 的 `HasPrefix(refund.RefundNo,
// "3CYM")`）因此是对的，只是它当时被当成了一条没有出处的约定。样例里的两个单号
// （merOrderId=`101771151dc8…`、refundOrderId=`1017159764568561`）也同以 `1017` 开头，
// 与那条规则自洽。
//
// **发了前缀就必须同时改比对**：`refundEchoMismatch` 那边不能再拿渠道回显的原文去比我们手里
// 的裸退款单号——那样每一次成功的退款都会被读成「对不上」，而它的后果是调用方拿同一个退款单号
// 再退一次。所以那一处改成两边都先解回内部单号再比（与查单那条路的比法逐字相同）。
//
// # 长度：退款单号要比支付单号短
//
// 规范给的上限是**小于 28 位**（含那 4 位前缀），而前缀是我们加的最长 4 位（sourceCode 由渠道
// 分配，见 config.go 的 RequireString）。所以内部退款单号自己不能超过 23 位——`service.Options`
// 生成退款单号时必须守住这一条，它不像支付单号那样有个宽裕的上限可挥霍。
