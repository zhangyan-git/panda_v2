// Package controller 是支付服务的接入层：解析请求、把结果写成响应。
//
// 它只有一个入口——渠道回调。小程序侧没有 payment 的 HTTP 面：发起支付是 order-service
// 编排的（它走 gRPC 调本服务，见 internal/rpc），客户端拿到的支付参数是那次调用的返回值。
// 支付方式列表、后台查单、退款这些前缀留给后面的切片。
//
// 与订单服务的接入层相比，这里有三件**不一样**的事：
//
//   - **没有身份**。回调来自渠道，不来自用户，所以这里没有 auth.Middleware、没有权限码、
//     也没有「身份只从令牌取」那条规矩。它的替代品是验签：`service.HandleNotification`
//     在碰报文里任何一个字段之前先验签，而路由是**故意不挂认证**的——挂了也没用，渠道
//     不会带我们的令牌，只会带它自己的签名。
//   - **不套 api.Success/api.Error**。那套信封是我们自己的客户端协议，渠道不认。应答要按
//     渠道约定的形状写（`provider.Ack`），所以这一层的输出走 writeCallbackAck 而不是 api。
//   - **不改状态**。所有对支付状态的改动都在 service 的事务里；这一层只负责把原始报文
//     原样递给它、把它的结论翻成应答。
//
// 错误 → 状态码的映射仍然集中在一处（payment_response.go），理由与订单服务一样：同一个
// 错误在不同入口必须是同一个码，否则前端得按接口记两套规矩。
