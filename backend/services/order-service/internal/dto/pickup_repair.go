package dto

// PickupRepairRequest 是「补建一张取货码订单」的请求体。
//
// # 为什么需要它
//
// 取货码那条路的顺序是**先扣钱、后建单**（扣减在咖啡机域与写余额流水是同一个事务）。中间
// 断掉时留下的是「钱扣了、单没建出来」：那笔钱在 device_balance_ledger 上留了痕（键是对方
// 单号），而订单那一侧什么都没有。合作方重投是第一个补救办法（整条路是幂等的），但他不再
// 重投时——他那边判成失败、或者他的重试窗口已经过去了——就得有人把这张单补出来。这个接口
// 就是那件事。
//
// # 为什么没有取货码那一格
//
// 补的是**钱已经扣过**的单：扣减撞上同一个 request_id 时会直接短路回当初那一笔，一分钱都
// 不会再扣（见咖啡机域的 DeductDeviceBalance）。所以这里不需要取货码——而没有取货码这个
// 事实本身是一道闸：这台设备的码非空时，空码永远不会通过校验，也就是说**这个接口在正常
// 情况下不可能引起一次新的扣款**，它只会把已经扣过的那一单补出来。
//
// 反过来说：如果一次补单被回「取货码不对」，那不是这条接口的毛病，而是**这笔钱从来没扣过**
// ——那一单不该补，该先去查合作方到底有没有发起过。
//
// # 字段与取货码那条报文一一对应
//
// 补单要重建的是同一张单，所以报文的形状原样保留：对方单号（幂等键，也是流水上的 request_id）、
// 设备序列号、机器报的饮品编号、备注。运维手上这些值的来源是 partner_call_logs 里那条调用
// 记录（它的请求体里有前三个，取货码那一格已被脱敏）。
type PickupRepairRequest struct {
	// ThirdPartyOrderNo 是对方单号。它不是「随便填一个」：这个值必须能在设备余额流水上找到
	// 对应的那一笔扣减，否则补不出来（见上面）。
	ThirdPartyOrderNo string `json:"thirdPartyOrderNo"`
	// DeviceSerial 是机器自己认识的那个编号（devices.serial_unique）。
	DeviceSerial string `json:"deviceSerial"`
	// DrinkCode 是机器报的饮品编号，用来重建那一行饮品（名称与目录价都从库里那一行取）。
	DrinkCode string `json:"drinkCode"`
	// Remark 是备注，可空。它会拼在「取货码购买」之后，与原始报文那条同形。
	Remark string `json:"remark"`
}
