// Package controller 是 partner-service 的接入层：解析请求、把结果写成响应。
//
// # 这里有两棵树，约定相反
//
//   - **后台树**（/v1/admin/partners、/v1/admin/partner-call-logs，见 admin_partner.go）。
//     每一条都挂四层（认证 → 平台账号闸门 → 实时授权 → 权限码），错误翻译成给运营看的中文。
//   - **开放接口树**（/v1/openapi/*，见 openapi.go）。**没有我们的令牌**——调用方是合作方的
//     机器，凭据是它自己签的 X-Signature。整棵树被 ingress.Guard 包着（见 routes/openapi.go），
//     验签、防重放、限流、调用日志都在那一段里，这一层是验签**之后**才被调到的。
//
// 两棵树的差别不只是「挂不挂认证」，还有**三处刻意的相反**：
//
//	              后台树                     开放接口树
//	身份           令牌（auth.Middleware）    签名（X-API-Key + X-Signature）
//	失败的答复     中文，给运营看              英文，给对接方的开发看
//	调用日志       走审计（谁改的）            走 partner_call_logs（谁调的）
//
// 中文与英文的差别不是随手定的：后台的读者是运营，他在页面上看到的每一句话都该是中文；开放
// 接口的读者是外部系统的开发者，他手上的是一份英文（或中英对照）的对接文档，而**网关那一段
// 的拒绝响应本来就是英文的**（见 ingress 的 unauthorizedBody）——同一个接口上先出现一句英文
// 401、再出现一句中文 400，对接方会以为撞上了两个不同的系统。
//
// 两棵树都在这一个包里，因为它们共享同一批请求解析与错误翻译的工具（admin_response.go）。
// 分开两个包会让那些工具要么重复一份、要么先抽一层「公共 controller」，而后者在一个只有两棵
// 树的模块里没有第二个用处。
