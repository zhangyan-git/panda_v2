// Package controller 是抽奖服务的 HTTP 层：解析请求、调业务层、把结果映射成 dto。
//
// # 一个动作一个方法，一棵路径一个 handler
//
// 与 order-service / coupon-service 同样的写法：`URL.Path` 去掉树根之后剩下的那一段自己
// 判分支，不让 mux 传参。理由是踩过的——mux 的 `{id}` 只吃一个路径段，`/{id}/draw` 注册在
// `/{id}` 之后就永远解析成 `id="draw"`，而那种错是**静默**的：路由还在，只是永远走不到。
//
// # 归属
//
// 后台那棵树（`/v1/admin/lottery/...`）的认证与权限码由装配处挂在每一条路由上（见
// routes.RegisterAdmin），controller 只读身份来记操作人；小程序那棵树
// （`/v1/miniapp/lottery/...`）只套认证，**归属由 requireConsumer + service 强制覆盖**
// 实现——「只能碰自己的参与与中奖」这件事权限码表达不了。
//
// # 这一层不做业务判断
//
// 它不校验状态机、不算进度、不碰余额。唯一被允许留在这里的判断是「这个查询串里的枚举值
// 写错了吗」，因为那是**接口的形状问题**而不是业务规则（写错一个字母会静默返回空列表，
// 调用方会以为「这个状态下确实没有数据」）。
