// Package routes 把 controller 挂到 HTTP 路由上，并按端各自注册一棵路径树。
//
// 三条不能破坏的约定（与 coffee-machine-service / order-service 同一套）：
//
//   - 认证由调用方注入，不由这里 new 一个。装配处（cmd/main.go）是唯一知道「哪个端该套
//     哪条中间件链」的地方；本包只保证「没给中间件就回 401」，绝不 fail-open。
//   - **一条路径只注册一次**。底层是 gorilla/mux，它的 HandleFunc 是往路由表里追加而不是
//     按路径合并：对同一个 path 调两次，先注册的那条会吃掉所有方法，后注册的永远到不了
//     ——症状是 GET 好用、POST 静默回 404。所以「GET 要读权限、POST 要写权限」写在同一张
//     byMethod 表里，由 routeFor 按方法各自套上权限中间件。
//   - 权限码写在注册处，不写在 handler 里。同一个树 handler 服务多个动作时，每个动作的
//     权限码在这里绑定；controller 里再判一次意味着有两处要同时改对。
//
// 路径的注册顺序不在这里体现（mux 的路由表里都是完整模式，没有前缀关系），但**树的划分**
// 有讲究：`/{id}/draw` 与 `/{id}` 是两条独立模式，而不是「/{id} 之后还有子路径」——
// 后者在 mux 里不成立（`{id}` 只吃一个路径段）。
//
// `routes/admin_test.go` 逐条断言「哪个方法落在哪个权限码上」，它是这个包唯一的测试，
// 也是唯一能在不碰数据库的前提下发现路由表串了的地方。
