COMMENT ON COLUMN orders.fortune_cards_expected IS '本单承诺发放的福卡张数，包含基础赠送与加购活动加赠';
COMMENT ON COLUMN orders.fortune_card_snapshot IS '承诺发放福卡的构成快照（基础赠送、各活动加赠）；发放结果与余额归账户服务';
