-- order/002：订单表和关键字段中文注释

COMMENT ON TABLE orders IS '订单主表：一次下单的事实，金额单位为分；买了哪几件东西见 order_lines。订单类型不存列，由行的 line_type 派生：有 membership 行的是会员订单，有 drink 行的是咖啡订单';
