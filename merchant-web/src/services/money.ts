/**
 * 金额在「分」与「元」之间的换算。
 *
 * 接口和库里金额一律是「分」的整数，页面按「元」展示。这个换算是全仓唯一的一份——单位
 * 错位（12.50 显示成 12.00）不会报错，只会静默算错钱，而同一个数在列表页和详情页上各
 * 算各的，两处迟早会漂移。
 *
 * 商户端是只读的，所以这里没有「元 → 分」那一半：没有录入，就没有把元换算回去的地方。
 */

/** 分 → 元。 */
export const fenToYuan = (fen?: number | null) => Number(fen ?? 0) / 100;

/** 展示用，固定两位小数。**不拼 ¥**：有的列本来就没有币种前缀，拼了就得多一个开关。 */
export const formatYuan = (fen?: number | null) => fenToYuan(fen).toFixed(2);
